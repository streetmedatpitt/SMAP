// Helper Functions
export const getUpcomingEvents = (maxEvents, category = 'all') => {
  let upcoming = eventsData.filter((event) => event.isUpcoming);
  if (category && category !== 'all') {
    upcoming = upcoming.filter((event) => event.category === category);
  }
  return typeof maxEvents === 'number' ? upcoming.slice(0, maxEvents) : upcoming;
};

export const getPastEvents = (limit) => {
  const past = eventsData.filter((event) => !event.isUpcoming);
  return typeof limit === 'number' ? past.slice(0, limit) : past;
};

export const getEventById = (id) => {
  if (!id) return null;
  // Support aliases
  if (id === 'annual-holiday-card-making-2025') {
    return eventsData.find((event) => event.id === 'holiday-card-making-2024') || null;
  }
  return eventsData.find((event) => event.id === id) || null;
};

